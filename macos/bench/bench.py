#!/usr/bin/env python3
#
# Benchmarks foot against other terminals (kitty and Ghostty, if they're
# installed), each with its default configuration and the same font:
# how fast they consume output, how fast they start, and what an idle
# window costs. The method is described in macos/bench/README.md.
#
# Usage: bench.py [--save] [options]   (make bench ARGS='...')
#
# The terminals' windows open on screen, one after the other: don't
# type into them, and leave the Mac alone until the run is done.
#
# The results (raw, results.json and results.md) go to
# build-release/bench/<date>/. With --save, also to macos/bench/, and
# their summary to .github/README.md (between its bench markers).

import argparse
import datetime
import json
import os
import plistlib
import re
import shutil
import statistics
import subprocess
import sys
import time

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
BENCH = os.path.join(ROOT, 'macos', 'bench')
README = os.path.join(ROOT, '.github', 'README.md')
README_BEGIN = '<!-- bench: generated by macos/bench/bench.py --save -->'
README_END = '<!-- /bench -->'

FONT = 'Menlo'
FONT_SIZE = 14
MiB = 1024 * 1024

# tbench.c's workloads
WORKLOADS = [
    ('ascii', 'ASCII text'),
    ('unicode', 'Unicode text'),
    ('dense_cells', 'Colored cells'),
    ('scroll', 'Scrolling'),
    ('scroll_region', 'Scrolling region'),
    ('cursor_motion', 'Cursor motion'),
]

# A process using more CPU than this (%) disturbs the measurements
BUSY_CPU = 40


class BenchError(Exception):
    pass


def log(msg):
    print(f'bench: {msg}', flush=True)


class Terminal:
    def __init__(self, kind, label, exe):
        self.kind = kind
        self.label = label
        self.exe = exe
        self.version = None

    def command(self, cols, rows, argv, empty_config):
        if self.kind == 'foot':
            return [self.exe, f'--config={empty_config}', '-o', f'font={FONT}:size={FONT_SIZE}',
                    f'--window-size-chars={cols}x{rows}', *argv]
        if self.kind == 'kitty':
            return [self.exe, '--config', 'NONE', '-o', f'font_family={FONT}', '-o', f'font_size={FONT_SIZE}',
                    '-o', f'initial_window_width={cols}c', '-o', f'initial_window_height={rows}c',
                    '-o', 'remember_window_size=no', '-o', 'macos_quit_when_last_window_closed=yes', *argv]
        if self.kind == 'ghostty':
            return [self.exe, '--config-default-files=false', f'--font-family={FONT}', f'--font-size={FONT_SIZE}',
                    f'--window-width={cols}', f'--window-height={rows}', '--window-save-state=never',
                    '--quit-after-last-window-closed=true',
                    '--confirm-close-surface=false', '-e', *argv]
        raise ValueError(self.kind)

    def read_version(self):
        out = subprocess.run([self.exe, '--version'], capture_output=True, text=True, timeout=60).stdout
        pattern = {'foot': r'version: (\S+)', 'kitty': r'kitty (\S+)', 'ghostty': r'Ghostty (\S+)'}[self.kind]
        m = re.search(pattern, out)
        self.version = m.group(1) if m else out.strip().split('\n')[0]


APPS = {
    'kitty': ('kitty', 'kitty.app/Contents/MacOS/kitty'),
    'ghostty': ('Ghostty', 'Ghostty.app/Contents/MacOS/ghostty'),
}


def find_terminals(args):
    terminals = []
    for kind in args.terminals.split(','):
        if kind == 'foot':
            for spec in args.foot or [os.path.join(ROOT, 'build-release/macos/foot.app/Contents/MacOS/foot')]:
                label, _, path = spec.rpartition('=')
                path = os.path.abspath(path)
                if not os.access(path, os.X_OK):
                    raise BenchError(f'{path}: no such program (make release builds it)')
                terminals.append(Terminal('foot', label or 'foot', path))
        elif kind in APPS:
            label, rel = APPS[kind]
            for d in ('/Applications', os.path.expanduser('~/Applications')):
                path = os.path.join(d, rel)
                if os.access(path, os.X_OK):
                    terminals.append(Terminal(kind, label, path))
                    break
            else:
                log(f'{label} is not installed, skipping it')
        else:
            raise BenchError(f'unknown terminal: {kind} (foot, kitty, ghostty)')
    if not terminals:
        raise BenchError('no terminals to benchmark')
    return terminals


def run_text(argv):
    try:
        return subprocess.run(argv, capture_output=True, text=True, timeout=60).stdout
    except (OSError, subprocess.SubprocessError):
        return ''


def system_info():
    info = {'machine': run_text(['sysctl', '-n', 'hw.model']).strip()}
    try:
        hw = json.loads(run_text(['system_profiler', 'SPHardwareDataType', '-json']))['SPHardwareDataType'][0]
        info['machine'] = hw['machine_name']
        info['model'] = hw['machine_model']
        info['chip'] = hw.get('chip_type') or hw.get('cpu_type', '?')
        info['memory'] = hw.get('physical_memory', '?')
        cores = hw.get('number_processors', '').split(':')
        if len(cores) == 4:
            info['cores'] = f'{cores[2]} performance and {cores[3]} efficiency cores'
    except (ValueError, KeyError, IndexError):
        pass

    info['macos'] = f"{run_text(['sw_vers', '-productVersion']).strip()} ({run_text(['sw_vers', '-buildVersion']).strip()})"
    info['display'] = main_display()

    batt = run_text(['pmset', '-g', 'batt'])
    m = re.search(r"drawing from '([^']+)'", batt)
    info['power'] = m.group(1) if m else '?'
    if re.search(r'lowpowermode\s+1', run_text(['pmset', '-g'])):
        info['power'] += ', Low Power Mode'
    return info


def main_display():
    """The main display: its name, resolution, refresh rate and scale"""
    try:
        gpus = json.loads(run_text(['system_profiler', 'SPDisplaysDataType', '-json']))['SPDisplaysDataType']
        for gpu in gpus:
            for d in gpu.get('spdisplays_ndrvs', []):
                if d.get('spdisplays_main') != 'spdisplays_yes':
                    continue
                pixels = d.get('_spdisplays_pixels', '')
                looks = d.get('_spdisplays_resolution', '')
                scale = ''
                try:
                    scale = f', scale {int(pixels.split(" x ")[0]) // int(looks.split(" x ")[0])}'
                except (ValueError, IndexError, ZeroDivisionError):
                    pass
                return f"{d.get('_name', '?')}, {looks.replace('.00Hz', ' Hz')}{scale}"
    except (ValueError, KeyError):
        pass
    return '?'


def screen_locked():
    try:
        root = plistlib.loads(subprocess.run(['ioreg', '-n', 'Root', '-d1', '-a'], capture_output=True).stdout)
        users = root[0]['IOConsoleUsers'] if isinstance(root, list) else root['IOConsoleUsers']
        return any(u.get('CGSSessionScreenIsLocked') for u in users)
    except (ValueError, KeyError, IndexError, plistlib.InvalidFileException):
        return False


def busy_processes(ignore=()):
    """Other processes using a lot of CPU (ps' %CPU decays over a minute)"""
    own = {os.getpid()}
    procs = []
    for line in run_text(['ps', '-Ao', 'pid=,ppid=,pcpu=,comm=']).splitlines():
        f = line.split(None, 3)
        if len(f) == 4:
            procs.append((int(f[0]), int(f[1]), float(f[2]), f[3]))
    for _ in range(4):
        own |= {pid for pid, ppid, _, _ in procs if ppid in own}
    return [(cpu, os.path.basename(comm)) for pid, _, cpu, comm in procs
            if pid not in own and cpu >= BUSY_CPU and os.path.basename(comm) not in ignore]


def busy_text(busy):
    return ', '.join(f'{name} ({cpu:.0f}%)' for cpu, name in sorted(busy, reverse=True))


def load_average():
    m = re.search(r'([\d.]+)', run_text(['sysctl', '-n', 'vm.loadavg']))
    return float(m.group(1)) if m else 0.0


def wait_until_ready(args):
    """Until the screen is unlocked, and nothing else keeps the CPU busy"""
    if screen_locked():
        log('the screen is locked; waiting until it is unlocked')
        while screen_locked():
            time.sleep(5)

    if args.force:
        return
    deadline = time.time() + args.wait * 60
    shown = None
    while True:
        busy = busy_processes(args.ignore.split(',') if args.ignore else ())
        if not busy:
            return
        names = busy_text(busy)
        if time.time() > deadline:
            raise BenchError(f'the Mac is busy ({names}); run again later, or with --force')
        if names != shown:
            log(f'waiting until the Mac is quiet: {names}')
            shown = names
        time.sleep(10)


class Launcher:
    def __init__(self, args, out_dir, tbench, display):
        self.args = args
        self.display = display
        self.out_dir = out_dir
        self.tbench = tbench
        self.empty_config = os.path.join(out_dir, 'empty.ini')
        open(self.empty_config, 'w').close()
        self.proc = None

    def start(self, term, cols, rows, argv, name):
        log_file = open(os.path.join(self.out_dir, 'raw', f'{name}.log'), 'ab')
        self.proc = subprocess.Popen(term.command(cols, rows, argv, self.empty_config),
                                     stdin=subprocess.DEVNULL, stdout=log_file, stderr=subprocess.STDOUT,
                                     start_new_session=True)
        log_file.close()
        return self.proc

    def close(self):
        proc, self.proc = self.proc, None
        if proc is None or proc.poll() is not None:
            return
        proc.terminate()
        try:
            proc.wait(10)
        except subprocess.TimeoutExpired:
            proc.kill()
            proc.wait()

    def measured(self, what, fn):
        """Runs a measurement; again if the screen was locked meanwhile.
        Stops when the display changed (e.g. it was switched off): the
        windows' sizes and frame rates depend on it."""
        for _ in range(3):
            wait_until_ready(self.args)
            try:
                result = fn()
            finally:
                self.close()
            time.sleep(1)
            display = main_display()
            if display != self.display:
                raise BenchError(f'the display changed during {what}: {self.display}, now {display}; '
                                 'the results so far are in raw/, measure again with the display on')
            if not screen_locked():
                return result
            log(f'the screen was locked during {what}; measuring it again')
        raise BenchError(f'{what}: the screen keeps getting locked')

    def throughput(self, term, cols, rows, name):
        path = os.path.join(self.out_dir, 'raw', f'{name}.txt')
        if os.path.exists(path):
            os.remove(path)
        proc = self.start(term, cols, rows, [self.tbench, 'run', path, str(self.args.runs)], name)

        t0 = time.time()
        done_at = None
        while proc.poll() is None:
            if done_at is None and os.path.exists(path) and open(path).read().endswith('done\n'):
                done_at = time.time()
            if done_at is not None and time.time() - done_at > 10:
                break  # done, but the terminal didn't quit
            if time.time() - t0 > 900:
                raise BenchError(f'{name}: no result after 15 minutes')
            time.sleep(0.5)

        size, samples, done = None, {}, False
        if os.path.exists(path):
            for line in open(path):
                f = line.split()
                if f[0] == 'size':
                    size = [int(x) for x in f[1:5]]
                elif f[0] == 'done':
                    done = True
                elif len(f) == 3:
                    samples.setdefault(f[0], []).append(int(f[1]) / MiB / float(f[2]))
        if not done:
            raise BenchError(f'{name}: tbench did not finish (see raw/{name}.log)')
        return {'size': size, 'samples': samples}

    def wait_for_mark(self, proc, mark, t0, name):
        while not os.path.exists(mark):
            if proc.poll() is not None:
                raise BenchError(f'{name}: the terminal exited (see raw/{name}.log)')
            if time.time() - t0 > 60:
                raise BenchError(f'{name}: the command did not start within a minute')
            time.sleep(0.005)
        return float(open(mark).read())

    def startup(self, term, cols, rows, name):
        mark = os.path.join(self.out_dir, 'raw', f'{name}.mark')
        if os.path.exists(mark):
            os.remove(mark)
        t0 = time.time()
        proc = self.start(term, cols, rows, [self.tbench, 'mark', mark], name)
        return (self.wait_for_mark(proc, mark, t0, name) - t0) * 1000

    def stat(self, pid):
        out = subprocess.run([self.tbench, 'stat', str(pid)], capture_output=True, text=True).stdout.split()
        if len(out) != 4:
            raise BenchError(f'could not read the statistics of process {pid}')
        return [int(x) for x in out]

    def idle(self, term, cols, rows, name):
        mark = os.path.join(self.out_dir, 'raw', f'{name}.mark')
        for path in (mark, mark + '.size'):
            if os.path.exists(path):
                os.remove(path)
        proc = self.start(term, cols, rows, [self.tbench, 'mark', mark], name)
        self.wait_for_mark(proc, mark, time.time(), name)

        time.sleep(5)  # settle; tbench has written the window's size meanwhile
        size = [int(x) for x in open(mark + '.size').read().split()] if os.path.exists(mark + '.size') else None
        a, ta = self.stat(proc.pid), time.monotonic()
        time.sleep(self.args.idle_seconds)
        b, tb = self.stat(proc.pid), time.monotonic()
        dt = tb - ta
        if size is not None and size[:2] != [cols, rows]:
            log(f'{term.label}: the idle window was {size[0]}x{size[1]}, not {cols}x{rows}')
        return {
            'size': size,
            'cpu_percent': (b[0] - a[0]) / 1e9 / dt * 100,
            'wakeups_per_second': ((b[1] + b[2]) - (a[1] + a[2])) / dt,
            'footprint_mib': b[3] / MiB,
        }


def rotated(items, n):
    n %= len(items)
    return items[n:] + items[:n]


def build_tbench():
    src = os.path.join(BENCH, 'tbench.c')
    exe = os.path.join(ROOT, 'build-release', 'bench', 'tbench')
    if not os.path.exists(exe) or os.path.getmtime(exe) < os.path.getmtime(src):
        os.makedirs(os.path.dirname(exe), exist_ok=True)
        subprocess.run(['xcrun', 'cc', '-O2', '-Wall', '-o', exe, src], check=True)
    return exe


def run(args):
    sizes = []
    for s in args.sizes.split(','):
        m = re.fullmatch(r'(\d+)x(\d+)', s)
        if not m:
            raise BenchError(f'{s}: not a size (e.g. 160x50)')
        sizes.append((int(m.group(1)), int(m.group(2))))

    terminals = find_terminals(args)
    tbench = build_tbench()
    for term in terminals:
        term.read_version()

    stamp = datetime.datetime.now()
    out_dir = args.out or os.path.join(ROOT, 'build-release', 'bench', stamp.strftime('%Y-%m-%d-%H%M%S'))
    os.makedirs(os.path.join(out_dir, 'raw'), exist_ok=True)

    # No display sleep, no idle sleep, while this runs
    subprocess.Popen(['caffeinate', '-dim', '-w', str(os.getpid())])

    results = {
        'date': stamp.strftime('%Y-%m-%d'),
        'system': system_info(),
        'terminals': [{'label': t.label, 'kind': t.kind, 'version': t.version} for t in terminals],
        'settings': {'font': f'{FONT} {FONT_SIZE}', 'sizes': [f'{c}x{r}' for c, r in sizes],
                     'rounds': args.rounds, 'runs': args.runs, 'startups': args.startups,
                     'idle_seconds': args.idle_seconds},
        'load_average': {'start': load_average()},
        'busy': {'start': busy_text(busy_processes())},
        'throughput': {},
        'startup': {},
        'idle': {},
    }

    log(f'{len(terminals)} terminal(s): ' + ', '.join(f'{t.label} {t.version}' for t in terminals))
    log(f'results in {out_dir}')
    log("the windows open on screen; don't type into them, and leave the Mac alone until the end")

    launcher = Launcher(args, out_dir, tbench, results['system']['display'])
    try:
        if args.only in (None, 'idle'):
            cols, rows = sizes[0]
            for term in terminals:  # warms up the caches; not counted
                launcher.measured(f'{term.label} warm-up', lambda: launcher.startup(term, cols, rows, f'{term.label}-warmup'))
            for i in range(args.startups):
                for term in rotated(terminals, i):
                    name = f'{term.label}-startup-{i + 1}'
                    ms = launcher.measured(name, lambda: launcher.startup(term, cols, rows, name))
                    results['startup'].setdefault(term.label, []).append(ms)
                    log(f'{term.label}: started in {ms:.0f} ms')
            for term in terminals:
                name = f'{term.label}-idle'
                log(f'{term.label}: an idle window, {args.idle_seconds} s')
                results['idle'][term.label] = launcher.measured(name, lambda: launcher.idle(term, cols, rows, name))

        if args.only in (None, 'throughput'):
            total = len(sizes) * args.rounds * len(terminals)
            n = 0
            for cols, rows in sizes:
                size = f'{cols}x{rows}'
                for r in range(args.rounds):
                    for term in rotated(terminals, r):
                        n += 1
                        name = f'{term.label}-{size}-{r + 1}'
                        log(f'[{n}/{total}] {term.label}, {size}, round {r + 1} of {args.rounds}')
                        res = launcher.measured(name, lambda: launcher.throughput(term, cols, rows, name))
                        entry = results['throughput'].setdefault(size, {}).setdefault(
                            term.label, {'size': res['size'], 'samples': {}})
                        if res['size'] != entry['size']:
                            log(f'{term.label}: the window size changed between rounds: {entry["size"]}, {res["size"]}')
                        for w, xs in res['samples'].items():
                            entry['samples'].setdefault(w, []).extend(xs)
    finally:
        launcher.close()

    results['load_average']['end'] = load_average()
    results['busy']['end'] = busy_text(busy_processes())

    with open(os.path.join(out_dir, 'results.json'), 'w') as f:
        json.dump(results, f, indent=2)
        f.write('\n')
    markdown = results_markdown(results)
    with open(os.path.join(out_dir, 'results.md'), 'w') as f:
        f.write(markdown)
    print()
    print(markdown)

    if args.save:
        shutil.copy(os.path.join(out_dir, 'results.json'), os.path.join(BENCH, 'results.json'))
        shutil.copy(os.path.join(out_dir, 'results.md'), os.path.join(BENCH, 'results.md'))
        update_readme(results)
        log('saved: macos/bench/results.md, macos/bench/results.json, .github/README.md')


