def median(xs):
    return statistics.median(xs) if xs else None


def spread(xs):
    """Half the range, relative to the median"""
    if len(xs) < 2:
        return ''
    return f' ±{(max(xs) - min(xs)) / 2 / statistics.median(xs) * 100:.0f}%'


def fmt(x, digits=0):
    return '–' if x is None else f'{x:.{digits}f}'


def row(cells):
    return '| ' + ' | '.join(cells) + ' |'


def best(values, higher):
    """Which of the values is the best (bold), when there are several"""
    known = [v for v in values if v is not None]
    if len(known) < 2:
        return [False] * len(values)
    target = max(known) if higher else min(known)
    return [v is not None and v == target for v in values]


def mismatched(results, size, label):
    want = [int(x) for x in size.split('x')]
    got = results['throughput'][size][label]['size']
    return got is not None and got[:2] != want


def throughput_table(results, size, with_spread):
    labels = [t['label'] for t in results['terminals'] if t['label'] in results['throughput'].get(size, {})]
    data = results['throughput'][size]
    lines = [row([f'MiB/s, {size} (higher is better)'] + labels), row(['---'] + ['--:'] * len(labels))]
    for w, title in WORKLOADS:
        values = [median(data[l]['samples'].get(w, [])) for l in labels]
        ok = [None if mismatched(results, size, l) else v for l, v in zip(labels, values)]
        bold = best(ok, higher=True)
        cells = []
        for l, v, b in zip(labels, values, bold):
            text = fmt(v) + (spread(data[l]['samples'].get(w, [])) if with_spread else '')
            if mismatched(results, size, l):
                text += ' †'
            cells.append(f'**{text}**' if b else text)
        lines.append(row([title] + cells))
    lines.append(row(['Window (pixels)'] + [
        '×'.join(str(x) for x in data[l]['size'][2:4]) if data[l]['size'] else '–' for l in labels]))
    notes = [f'† {l}\'s window was {data[l]["size"][0]}x{data[l]["size"][1]}, not {size}: not comparable.'
             for l in labels if mismatched(results, size, l)]
    return '\n'.join(lines) + ('\n\n' + '\n'.join(notes) if notes else '')


def resources_table(results, with_spread):
    labels = [t['label'] for t in results['terminals'] if t['label'] in results['idle'] or t['label'] in results['startup']]
    lines = [row(['Lower is better'] + labels), row(['---'] + ['--:'] * len(labels))]

    startup = [results['startup'].get(l, []) for l in labels]
    values = [median(xs) for xs in startup]
    cells = [fmt(v) + (spread(xs) if with_spread else '') for v, xs in zip(values, startup)]
    lines.append(row(['Startup, until the command runs (ms)'] +
                     [f'**{c}**' if b else c for c, b in zip(cells, best(values, higher=False))]))

    size = results['settings']['sizes'][0]
    want = [int(x) for x in size.split('x')]
    wrong = [l for l in labels if (results['idle'].get(l, {}).get('size') or want)[:2] != want]
    for key, title, digits in [('footprint_mib', f'Memory, idle window {size} (MiB)', 0),
                               ('cpu_percent', 'CPU, idle window (%)', 2),
                               ('wakeups_per_second', 'Wakeups, idle window (per second)', 1)]:
        values = [results['idle'].get(l, {}).get(key) for l in labels]
        cells = [fmt(v, digits) + (' †' if l in wrong else '') for l, v in zip(labels, values)]
        lines.append(row([title] + [f'**{c}**' if b else c for c, b in zip(cells, best(
            [None if v is None or l in wrong else round(v, digits) for l, v in zip(labels, values)],
            higher=False))]))
    notes = [f"† {l}'s idle window was {'x'.join(map(str, results['idle'][l]['size'][:2]))}, not {size}: "
             'not comparable.' for l in wrong]
    return '\n'.join(lines) + ('\n\n' + '\n'.join(notes) if notes else '')


def versions(results):
    return ', '.join(f"{t['label']} {t['version']}" for t in results['terminals'])


def system_lines(results):
    s = results['system']
    cores = f", {s['cores']}" if 'cores' in s else ''
    return [
        f"* {s.get('machine', '?')} ({s.get('model', '?')}): {s.get('chip', '?')}{cores}, {s.get('memory', '?')}",
        f"* macOS {s.get('macos', '?')}; display: {s.get('display', '?')}; power: {s.get('power', '?')}",
        f'* {versions(results)}',
    ]


def results_markdown(results):
    st = results['settings']
    out = [
        '# Benchmark results',
        '',
        f"Measured on {results['date']} with `make bench` "
        f"([macos/bench/bench.py](bench.py), method: [README.md](README.md)).",
        '',
        *system_lines(results),
        f"* Each terminal with its default configuration, font {st['font']}.",
        f"* Throughput: the median of {st['rounds'] * st['runs']} runs per workload "
        f"({st['rounds']} launches of each terminal, alternating, {st['runs']} runs each), ± half their range.",
        f"* Startup: the median of {st['startups']} launches, after one to warm up. "
        f"Idle: one window, for {st['idle_seconds']} s.",
        f"* Load average (1 minute): {results['load_average']['start']:.2f} at the start, "
        f"{results['load_average'].get('end', 0):.2f} at the end.",
    ]
    busy = results.get('busy', {})
    if busy.get('start') or busy.get('end'):
        out.append(f"* Busy meanwhile: {busy.get('start') or 'nothing'} at the start, "
                   f"{busy.get('end') or 'nothing'} at the end.")
    out.append('')
    for size in st['sizes']:
        if size in results['throughput']:
            out += [f'## Throughput, {size}', '', throughput_table(results, size, with_spread=True), '']
    if results['startup'] or results['idle']:
        out += ['## Startup, and an idle window', '', resources_table(results, with_spread=True), '']
    return '\n'.join(out)


def readme_markdown(results):
    st = results['settings']
    out = []
    size = st['sizes'][0]
    if size in results['throughput']:
        out += [throughput_table(results, size, with_spread=False), '']
    if results['startup'] or results['idle']:
        out += [resources_table(results, with_spread=False), '']
    s = results['system']
    display = s.get('display', '?')
    m = re.search(r'(\d+) x (\d+) @ ([\d.]+) Hz(?:, scale (\d+))?', display)
    if m:
        scale = f' (scale {m.group(4)})' if m.group(4) not in (None, '1') else ''
        display = f'{m.group(1)}×{m.group(2)} display at {m.group(3)} Hz{scale}'
    larger = [x for x in st['sizes'][1:] if x in results['throughput']]
    out.append(
        f"{s.get('machine', '?')} ({s.get('chip', '?')}, {s.get('memory', '?')}), "
        f"macOS {s.get('macos', '?').split(' ')[0]}, a {display}; {versions(results)}; "
        f"each with its default configuration and {st['font']}, on {results['date']}. "
        f"[All results{' (and a ' + ', '.join(larger) + ' window)' if larger else ''}]"
        '(../macos/bench/results.md), and [how they are measured](../macos/bench/README.md); '
        '`make bench` measures them on your Mac.')
    return '\n'.join(out)


def update_readme(results):
    text = open(README).read()
    begin, end = text.find(README_BEGIN), text.find(README_END)
    if begin < 0 or end < begin:
        log(f'.github/README.md has no bench markers ({README_BEGIN} ... {README_END}); not updated')
        return
    text = text[:begin + len(README_BEGIN)] + '\n' + readme_markdown(results) + '\n' + text[end:]
    with open(README, 'w') as f:
        f.write(text)


def main():
    p = argparse.ArgumentParser(description='Benchmarks foot against kitty and Ghostty (macos/bench/README.md).')
    p.add_argument('--foot', action='append', metavar='[LABEL=]PATH',
                   help='a foot to benchmark (default: the release build); give several to compare them, '
                        'e.g. --foot before=/Applications/foot.app/Contents/MacOS/foot '
                        '--foot after=build-release/macos/foot.app/Contents/MacOS/foot')
    p.add_argument('--terminals', default='foot,kitty,ghostty', help='default: %(default)s')
    p.add_argument('--sizes', default='160x50,400x88', help='window sizes (columns x rows), default: %(default)s')
    p.add_argument('--rounds', type=int, default=3, help='launches per terminal and size, default: %(default)s')
    p.add_argument('--runs', type=int, default=3, help='runs of each workload per launch, default: %(default)s')
    p.add_argument('--startups', type=int, default=5, help='launches to measure the startup, default: %(default)s')
    p.add_argument('--idle-seconds', type=int, default=30, help='default: %(default)s')
    p.add_argument('--only', choices=['throughput', 'idle'], help='only the throughput, or only startup and idle')
    p.add_argument('--wait', type=float, default=10,
                   help='minutes to wait for a quiet Mac, before giving up, default: %(default)s')
    p.add_argument('--force', action='store_true', help="don't wait for a quiet Mac")
    p.add_argument('--ignore', metavar='NAME,...',
                   help="processes that don't count when waiting for a quiet Mac (e.g. one stuck at 100%%)")
    p.add_argument('--save', action='store_true',
                   help='save the results in macos/bench/, and their summary in .github/README.md')
    p.add_argument('--out', help='where the results go, default: build-release/bench/<date>/')
    p.add_argument('--report', metavar='RESULTS.JSON', help="don't measure: (re)write the reports of a results.json")
    args = p.parse_args()

    try:
        if args.report:
            results = json.load(open(args.report))
            print(results_markdown(results))
            if args.save:
                update_readme(results)
        else:
            run(args)
    except BenchError as e:
        sys.exit(f'bench: {e}')
    except KeyboardInterrupt:
        sys.exit(130)


if __name__ == '__main__':
    main()
