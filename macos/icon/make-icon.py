#!/usr/bin/env python3
#
# Generates foot's macOS application icon: foot.svg, and from it
# foot.icns (needs rsvg-convert from librsvg, and iconutil).
#
# The artwork is upstream's logo (icons/hicolor/scalable/apps/foot.svg),
# laid out on macOS' icon grid: a 824x824 superellipse ("squircle") on a
# 1024x1024 canvas, with a drop shadow.
#
# Usage: macos/icon/make-icon.py

import math
import os
import shutil
import subprocess
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))

CANVAS = 1024
BODY = 824                      # Icon body, centered
ORIGIN = (CANVAS - BODY) / 2

# Upstream's logo: a 96x96 terminal at (16,16), on a 128x128 canvas
UPSTREAM_BG = 96
UPSTREAM_OFS = 16

FG = '#fbf1c7'

# Upstream's logo is drawn for small sizes, and fills the terminal. At
# icon sizes, scale it down, and give it some room: the content's
# bounding box (in body coordinates), and where it goes
CONTENT_BOX = (166, 139)        # Top-left of the foot, in body coordinates
CONTENT_SCALE = 0.72
CONTENT_POS = (262, 250)


def squircle(x, y, size, n=5.0, steps=720):
    """Superellipse |x|^n + |y|^n = 1, as an SVG path"""
    r = size / 2
    cx, cy = x + r, y + r
    points = []
    for i in range(steps):
        t = 2 * math.pi * i / steps
        c, s = math.cos(t), math.sin(t)
        px = cx + r * math.copysign(abs(c) ** (2 / n), c)
        py = cy + r * math.copysign(abs(s) ** (2 / n), s)
        points.append(f'{px:.2f},{py:.2f}')
    return 'M ' + ' L '.join(points) + ' Z'


def svg():
    body = squircle(ORIGIN, ORIGIN, BODY)
    inset = squircle(ORIGIN + 3, ORIGIN + 3, BODY - 6)
    scale = BODY / UPSTREAM_BG

    # Maps upstream's coordinates onto the icon body, then scales and
    # moves the content into place
    upstream = (f'translate({CONTENT_POS[0]},{CONTENT_POS[1]}) '
                f'scale({CONTENT_SCALE}) '
                f'translate({-CONTENT_BOX[0]},{-CONTENT_BOX[1]}) '
                f'translate({ORIGIN:.2f},{ORIGIN:.2f}) scale({scale:.6f}) '
                f'translate({-UPSTREAM_OFS},{-UPSTREAM_OFS})')

    return f'''<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by make-icon.py; based on upstream foot's logo (MIT) -->
<svg xmlns="http://www.w3.org/2000/svg" width="{CANVAS}" height="{CANVAS}" viewBox="0 0 {CANVAS} {CANVAS}">
 <defs>
  <linearGradient id="bg" x1="0" y1="0" x2="0" y2="1">
   <stop offset="0" stop-color="#3a3a3a"/>
   <stop offset="1" stop-color="#1e1e1e"/>
  </linearGradient>
  <linearGradient id="rim" x1="0" y1="0" x2="0" y2="1">
   <stop offset="0" stop-color="#ffffff" stop-opacity="0.22"/>
   <stop offset="1" stop-color="#ffffff" stop-opacity="0.04"/>
  </linearGradient>
  <filter id="shadow" x="-20%" y="-20%" width="140%" height="140%">
   <feGaussianBlur in="SourceAlpha" stdDeviation="14"/>
   <feOffset dy="12" result="blur"/>
   <feComponentTransfer><feFuncA type="linear" slope="0.35"/></feComponentTransfer>
   <feMerge><feMergeNode/><feMergeNode in="SourceGraphic"/></feMerge>
  </filter>
 </defs>
 <g filter="url(#shadow)">
  <path d="{body}" fill="url(#bg)"/>
 </g>
 <path d="{inset}" fill="none" stroke="url(#rim)" stroke-width="5"/>
 <g transform="{upstream}" fill="{FG}">
  <g transform="matrix(0.85714209,0,0,0.85714209,3.4285132,-145.99985)">
   <path d="m 37.0057,207.12866 c -0.9539,-0.24232 -1.8766,-0.41748 -2.7117,-0.49721 -4.1121,-0.39258 -5.433,-0.0326 -7.5067,2.04908 -2.8434,2.85385 -2.2667,6.90676 1.4644,10.38038 8.0896,7.53109 8.2202,12.581 0.4808,18.2752 -3.1863,2.34409 -5.492,7.85321 -4.4994,10.73911 1.2501,3.63469 6.0098,5.02447 10.1635,2.97341 3.8964,-1.92373 8.3104,-8.49971 11.3208,-16.36234 0.2509,-0.65526 0.4966,-1.31942 0.7268,-1.9912 0.6909,-2.01525 1.2796,-4.09527 1.7466,-6.17933 1.4109,-6.29466 1.0666,-11.19321 -0.9956,-14.13789 -1.287,-1.83788 -6.056,-4.19923 -10.1892,-5.24924 z"/>
   <g transform="translate(-1890.6933,-335.56903)">
    <ellipse cx="1934.6934" cy="540.29291" rx="2" ry="2.2761035"/>
    <ellipse cx="1939.0691" cy="543.35553" rx="1.6242591" ry="1.7864922"/>
    <ellipse cx="1941.3607" cy="547.06903" rx="1.33263" ry="1.5"/>
    <ellipse cx="1921.8835" cy="536.06903" rx="3.8097539" ry="4.5"/>
    <ellipse cx="1929.1934" cy="537.56903" rx="2.5" ry="3"/>
   </g>
  </g>
  <rect x="48" y="64" width="22" height="4"/>
 </g>
</svg>
'''


def main():
    svg_path = os.path.join(HERE, 'foot.svg')
    with open(svg_path, 'w') as f:
        f.write(svg())

    with tempfile.TemporaryDirectory() as tmp:
        iconset = os.path.join(tmp, 'foot.iconset')
        os.mkdir(iconset)
        for size in (16, 32, 128, 256, 512):
            for scale in (1, 2):
                px = size * scale
                name = f'icon_{size}x{size}{"@2x" if scale == 2 else ""}.png'
                subprocess.run(
                    ['rsvg-convert', '-w', str(px), '-h', str(px), svg_path,
                     '-o', os.path.join(iconset, name)], check=True)

        subprocess.run(
            ['iconutil', '-c', 'icns', iconset, '-o', os.path.join(HERE, 'foot.icns')],
            check=True)

        shutil.copy(os.path.join(iconset, 'icon_512x512@2x.png'),
                    os.path.join(tmp, 'preview.png'))
        preview = os.environ.get('FOOT_ICON_PREVIEW')
        if preview:
            shutil.copy(os.path.join(tmp, 'preview.png'), preview)


if __name__ == '__main__':
    main()
